def sha256(path):
    with Path(path).open('rb') as source:
        return hashlib.file_digest(source, 'sha256').hexdigest()


def run(command, **kwargs):
    return subprocess.run(command, check=True, capture_output=True, **kwargs)


def wait_with_usage(proc, started):
    """Reap this encoder and report measured usage without a GNU time dependency.

    wait4 reports the encoder's own peak, unlike cumulative RUSAGE_CHILDREN.
    Platforms without wait4 explicitly report an unavailable RSS measurement.
    """
    peak = None
    if hasattr(os, 'wait4'):
        _, status, usage = os.wait4(proc.pid, 0)
        proc.returncode = os.waitstatus_to_exitcode(status)
        peak = usage.ru_maxrss / 1024 if sys.platform == 'darwin' else usage.ru_maxrss
    else:
        proc.wait()
    return {
        'elapsed_seconds': round(time.perf_counter() - started, 6),
        'peak_rss_kib': peak,
        'peak_rss_method': 'wait4' if peak is not None else 'unavailable',
    }


def make_audio(spec, temp):
    samples = array.array('h', [0]) * (SAMPLE_RATE * spec['duration'])
    truth = []
    for index, entry in enumerate(SPEECH.get(spec['id'], [])):
        script = temp / f'speech-{index}.txt'
        script.write_text(entry['text'], encoding='utf-8')
        audio = temp / f'speech-{index}.wav'
        # The temporary filename is generated by us; no user-supplied filter text.
        run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-nostdin', '-y',
             '-filter_threads', '1', '-f', 'lavfi', '-i', f'flite=textfile={script}:voice={entry["voice"]}',
             '-ac', '1', '-ar', str(SAMPLE_RATE), '-c:a', 'pcm_s16le', '-threads', '1', str(audio)])
        with wave.open(str(audio), 'rb') as stream:
            pcm = array.array('h', stream.readframes(stream.getnframes()))
        offset = round(entry['start'] * SAMPLE_RATE)
        if offset + len(pcm) > len(samples):
            raise RuntimeError(f'{spec["id"]}: speech would be truncated')
        samples[offset:offset + len(pcm)] = pcm
        truth.append({**entry, 'end': round((offset + len(pcm)) / SAMPLE_RATE, 6),
                      'alignment': 'utterance extent from synthesis, not word alignment'})
    # Action/mixed audio combines a quiet carrier and exact 100 ms sync tones.
    if spec['id'] in ('action_motion', 'mixed_nonverbal'):
        for index in range(len(samples)):
            t = index / SAMPLE_RATE
            if spec['id'] == 'action_motion' or t >= 5:
                tone = 450 * math.sin(2 * math.pi * 180 * t)
                if any(marker <= t < marker + 0.1 for marker in spec['markers']):
                    tone += 12000 * math.sin(2 * math.pi * 1000 * t)
                samples[index] = max(-32768, min(32767, samples[index] + round(tone)))
    output = temp / 'audio.wav'
    with wave.open(str(output), 'wb') as stream:
        stream.setnchannels(1)
        stream.setsampwidth(2)
        stream.setframerate(SAMPLE_RATE)
        stream.writeframes(samples.tobytes())
    return output, truth


def label(draw, text, xy, fill='#e7ecf6', font=FONT):
    draw.text(xy, text, font=font, fill=fill)


def frame(spec, frame_index, speech):
    t = frame_index / FPS
    width, height = spec['size']
    scene = sum(t >= cut for cut in spec['cuts'])
    image = Image.new('RGB', (width, height), ['#111827', '#1b2433', '#182d2d', '#282038'][scene % 4])
    draw = ImageDraw.Draw(image)
    draw.rectangle((0, 0, width, 42), fill='#090d14')
    label(draw, 'SYNTHETIC BENCHMARK', (16, 11), '#9baac5', SMALL)
    label(draw, f'{t:06.2f}s / F{frame_index:04d}', (width - 176, 11), '#b8dcd2', SMALL)
    boxes = []
    kind = spec['id']
    if kind == 'spoken_interview':
        label(draw, 'Keep the source. Shape the story.', (34, 64), font=BOLD)
        active = next((s['speaker'] for s in speech if s['start'] <= t < s['end']), None)
        for name, x, color in [('A', 158, '#69ceb7'), ('B', 460, '#a8a1ed')]:
            draw.rounded_rectangle((x - 104, 113, x + 104, 308), radius=18, fill='#202c40', outline=color if active == name else '#364458', width=3)
            draw.ellipse((x - 32, 140, x + 32, 204), fill=color)
            draw.rounded_rectangle((x - 53, 211, x + 53, 274), radius=22, fill=color)
            label(draw, 'Speaker ' + name, (x - 41, 281), color, SMALL)
            boxes.append({'subject': name, 'box': [x - 53, 140, 106, 134]})
    elif kind == 'tutorial_screen':
        draw.rounded_rectangle((22, 60, 618, 321), radius=10, fill='#e8edf4')
        draw.rectangle((22, 60, 618, 90), fill='#36445a')
        label(draw, 'Example editor — generated interface', (36, 67), font=SMALL)
        for index, title in enumerate(['1  Choose source', '2  Set boundaries', '3  Export & review']):
            y = 112 + index * 61
            draw.rounded_rectangle((42, y, 267, y + 43), radius=7, fill='#b0e2d5' if scene == index else '#d4dce8')
            label(draw, title, (54, y + 12), '#172538')
        draw.rectangle((304, 111, 594, 264), fill='#24374d')
        for index in range(9):
            y = 126 + index * 13
            draw.line((321, y, 390 + (index * 21) % 180, y), fill='#a6bace', width=3)
        draw.rectangle((314, 278, 583, 299), fill='#73c6af')
        cursor_x = 160 + int(335 * ((t % 8) / 8))
        cursor_y = 134 + 61 * scene
        draw.polygon([(cursor_x, cursor_y), (cursor_x + 13, cursor_y + 20), (cursor_x + 6, cursor_y + 18)], fill='#d05045')
        boxes.append({'subject': 'essential-screen', 'box': [22, 60, 596, 261]})
    else:
        portrait = kind == 'portrait_unicode'
        top = 100 if portrait else 72
        bottom = height - 58
        for x in range(20, width, 40):
            draw.line((x, top, x, bottom), fill='#324057')
        for y in range(top, bottom, 40):
            draw.line((20, y, width - 20, y), fill='#324057')
        cycle = (t % 8) / 8
        ramp = 2 * cycle if cycle < 0.5 else 2 * (1 - cycle)
        x = round(50 + (width - 100) * ramp)
        y = round((top + bottom) / 2 + 35 * math.sin(t * math.pi / 2))
        if scene % 2:
            y = round((top + bottom) / 2 - 35 * math.sin(t * math.pi / 2))
        draw.rounded_rectangle((x - 20, y - 20, x + 20, y + 20), radius=5, fill='#e9c56b')
        draw.line((x, y - 8, x, y + 8), fill='#2d3542', width=2)
        draw.line((x - 8, y, x + 8, y), fill='#2d3542', width=2)
        boxes.append({'subject': 'gold-square', 'box': [x - 20, y - 20, 40, 40]})
        label(draw, 'Motion / direction / scene cuts', (20, 57), font=SMALL)
        if portrait:
            label(draw, 'Portrait · café', (30, height - 115), font=BOLD)
            label(draw, 'No audio stream', (30, height - 85), '#b9c6da')
    marker = any(mark <= t < mark + 2 / FPS for mark in spec['markers'])
    if marker:
        draw.rectangle((0, height - 35, width, height), fill='#ffffff')
        label(draw, 'SYNC FLASH + 1 kHz TONE', (16, height - 28), '#000000', SMALL)
    else:
        label(draw, f'{spec["genre"]} · scene {scene + 1}', (16, height - 27), '#93a3bc', SMALL)
    return image, {'frame': frame_index, 'time': round(t, 6), 'scene': scene, 'sync_flash': marker, 'subjects': boxes}


def probe(path):
    return json.loads(run(['ffprobe', '-v', 'error', '-show_format', '-show_streams', '-of', 'json', str(path)]).stdout)


def verify(path, spec):
    metadata = probe(path)
    video = next(s for s in metadata['streams'] if s['codec_type'] == 'video')
    assert [video['width'], video['height']] == spec['size']
    assert abs(float(metadata['format']['duration']) - spec['duration']) <= 1 / FPS
    assert any(s['codec_type'] == 'audio' for s in metadata['streams']) == spec['audio']
    run(['ffmpeg', '-hide_banner', '-v', 'error', '-nostdin', '-threads', '1', '-i', str(path), '-f', 'null', '-'])
    return metadata


def generate(spec, output_dir, evidence_dir):
    started = time.perf_counter()
    output = output_dir / spec['filename']
    with tempfile.TemporaryDirectory(prefix='vektri-fixture-') as name:
        temp = Path(name)
        audio, speech = make_audio(spec, temp) if spec['audio'] else (None, [])
        staging = temp / 'fixture.mp4'
        args = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-nostdin', '-y', '-threads', '1', '-filter_threads', '1',
                '-f', 'rawvideo', '-pixel_format', 'rgb24', '-video_size', 'x'.join(map(str, spec['size'])),
                '-framerate', str(FPS), '-i', 'pipe:0']
        if audio:
            args += ['-i', str(audio)]
        args += ['-map', '0:v'] + (['-map', '1:a'] if audio else [])
        args += ['-c:v', 'libx264', '-threads', '1', '-preset', 'veryfast', '-crf', '22', '-pix_fmt', 'yuv420p',
                 '-fflags', '+bitexact', '-flags:v', '+bitexact', '-map_metadata', '-1', '-metadata', 'creation_time=1970-01-01T00:00:00Z']
        if audio:
            args += ['-c:a', 'aac', '-b:a', '64k', '-flags:a', '+bitexact']
        args += ['-movflags', '+faststart', str(staging)]
        encode_started = time.perf_counter()
        proc = subprocess.Popen(args, stdin=subprocess.PIPE, stderr=subprocess.PIPE)
        frame_truth = []
        try:
            for index in range(spec['duration'] * FPS):
                image, truth = frame(spec, index, speech)
                if index == FPS * 3:
                    image.save(output_dir / f'{spec["id"]}.jpg', quality=88)
                proc.stdin.write(image.tobytes())
                frame_truth.append(truth)
            proc.stdin.close()
            stderr = proc.stderr.read().decode('utf-8', 'replace')
            measurements = wait_with_usage(proc, encode_started)
            if proc.returncode != 0:
                raise RuntimeError(stderr)
        except BaseException:
            proc.kill()
            proc.wait()
            raise
        metadata = verify(staging, spec)
        shutil.copyfile(staging, output.with_suffix('.pending.mp4'))
        os.replace(output.with_suffix('.pending.mp4'), output)
        truth = {**spec, 'fps': FPS, 'speech': speech, 'caption_alignment': 'No word timestamps supplied; test ASR must infer them from audio.',
                 'sync_markers': [{'time': mark, 'tone_duration': 0.1, 'flash_duration': 2 / FPS, 'tone_hz': 1000} for mark in spec['markers']],
                 'frames': frame_truth}
        (output_dir / f'{spec["id"]}.truth.json').write_text(json.dumps(truth, indent=2, ensure_ascii=False) + '\n')
        measurements['generation_and_verify_seconds'] = round(time.perf_counter() - started, 3)
        entry = {**spec, 'sha256': sha256(output), 'bytes': output.stat().st_size, 'measurements': measurements,
                 'validation': {'decode': 'passed', 'dimensions': 'passed', 'duration_tolerance_seconds': 1 / FPS, 'audio_presence': 'passed'},
                 'provenance': {'source': 'original procedural fixture', 'synthetic': True, 'permission_status': 'generated for this project',
                                'speech_engine': 'system Flite 2.2 via FFmpeg' if speech else None,
                                'human_recording': False, 'asr_result': False}}
        (evidence_dir / f'fixtures-{spec["id"]}-probe.json').write_text(json.dumps(metadata, indent=2) + '\n')
        print(f'{spec["filename"]}: {entry["bytes"]:,} bytes; {measurements["generation_and_verify_seconds"]}s; FFmpeg peak {measurements["peak_rss_kib"]} KiB', flush=True)
        return entry


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'fixtures')
    parser.add_argument('--evidence', type=Path, default=ROOT / 'evidence')
    parser.add_argument('--force', action='store_true', help='Replace only the named generated fixtures.')
    parser.add_argument('--verify', action='store_true', help='Verify existing fixture hashes, streams and full decode without generating.')
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    args.evidence.mkdir(parents=True, exist_ok=True)
    if args.verify:
        manifest = json.loads((args.output / 'manifest.json').read_text())
        for spec in manifest['fixtures']:
            path = args.output / spec['filename']
            assert sha256(path) == spec['sha256'], path
            verify(path, spec)
        invalid = subprocess.run(['ffprobe', '-v', 'error', str(args.output / 'corrupt-input.mp4')], capture_output=True)
        assert invalid.returncode != 0
        print('PASS: hashes, dimensions, duration, audio presence, full decode, corrupt-input rejection.')
        return
    if not args.force and any((args.output / s['filename']).exists() for s in SPECS):
        parser.error('Fixtures already exist; use --verify or explicitly --force to regenerate.')
    start = time.perf_counter()
    entries = [generate(spec, args.output, args.evidence) for spec in SPECS]
    (args.output / 'corrupt-input.mp4').write_bytes(b'Vektri deliberately corrupt media fixture\x00\xff\x00')
    screenshots = [Image.open(args.output / f'{spec["id"]}.jpg').convert('RGB') for spec in SPECS]
    contact = Image.new('RGB', (960, 480), '#0b0f17')
    for index, screenshot in enumerate(screenshots):
        screenshot.thumbnail((310, 210))
        contact.paste(screenshot, ((index % 3) * 320, (index // 3) * 240))
    contact.save(args.evidence / 'fixtures-contact-sheet.jpg', quality=90)
    manifest = {'schema_version': 1, 'generator': 'scripts/generate_fixtures.py', 'determinism': 'Fixed arithmetic, scripts, frame rate and metadata; binary hashes depend on FFmpeg, Flite, Pillow and font versions.',
                'ffmpeg_version': run(['ffmpeg', '-version']).stdout.decode().splitlines()[0], 'pillow_version': pillow_version,
                'font': {'path': str(FONT_PATH), 'sha256': sha256(FONT_PATH)}, 'fixtures': entries,
                'corrupt_fixture': {'filename': 'corrupt-input.mp4', 'sha256': sha256(args.output / 'corrupt-input.mp4')},
                'total_generation_seconds': round(time.perf_counter() - start, 3),
                'python_peak_rss_kib': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
                'limitations': ['Synthetic mechanics only; no evidence of sports, gameplay or real-world semantic understanding.',
                               'Synthetic speech tests the real ASR path but is not human speech quality validation.',
                               'Utterance timing is known; word alignment is not fabricated.', 'No variable-frame-rate, rotation metadata or multi-audio fixture in this core set.']}
    (args.output / 'manifest.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    (args.evidence / 'fixtures-generation.json').write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + '\n')
    print(f'Complete: {len(entries)} valid fixtures, one invalid fixture, {manifest["total_generation_seconds"]}s total.')


if __name__ == '__main__':
    main()
